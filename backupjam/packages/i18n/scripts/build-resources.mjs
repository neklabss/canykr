// Generates src/generated/resources.ts from locales/_registry.json + locales/<tag>.json.
// Adding a language = add a JSON file + a registry entry. No application code changes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(join(root, 'locales/_registry.json'), 'utf8'));
const messages = {};
for (const l of registry.locales) {
  messages[l.tag] = JSON.parse(readFileSync(join(root, 'locales', `${l.tag}.json`), 'utf8'));
}
mkdirSync(join(root, 'src/generated'), { recursive: true });
const header = '// AUTO-GENERATED by scripts/build-resources.mjs — do not edit by hand.\n/* eslint-disable */\n';
writeFileSync(join(root, 'src/generated/registry.ts'), `${header}export const REGISTRY = ${JSON.stringify(registry, null, 2)} as const;\n`);
writeFileSync(join(root, 'src/generated/resources.ts'), `${header}export { REGISTRY } from './registry';\nexport const MESSAGES: Record<string, Record<string, string>> = ${JSON.stringify(messages, null, 2)};\n`);
